export function localPath(locale, path = '') {
  return `${locale === 'id' ? '/id' : ''}${path}` || '/';
}

export function campaignMetadata(locale = 'en', site = 'world', path = '', title) {
  const c = copy[locale];
  const base = site === 'author' ? AUTHOR_URL : WORLD_URL;
  const pageTitle = title || (site === 'author' ? 'D.C. Barletta | Biologist. Software Engineer. Worldbuilder.' : 'Fault Lines — World of Tethys · Book II');
  return {
    title: { absolute: pageTitle },
    description: site === 'author' ? c.authorBio : c.bookBody,
    alternates: {
      canonical: `${base}${localPath(locale, path)}`,
      languages: { en: `${base}${localPath('en', path)}`, id: `${base}${localPath('id', path)}`, 'x-default': `${base}${localPath('en', path)}` },
    },
    openGraph: { title: pageTitle, description: c.tagline, url: `${base}${localPath(locale, path)}`, locale: locale === 'id' ? 'id_ID' : 'en_US', alternateLocale: locale === 'id' ? 'en_US' : 'id_ID', type: 'website', images: [{ url: `${base}/fault-lines-card.png`, width: 1200, height: 630, alt: 'World of Tethys — Fault Lines — D.C. Barletta' }] },
    twitter: { card: 'summary_large_image', title: pageTitle, description: c.tagline, images: [`${base}/fault-lines-card.png`] },
  };
}
